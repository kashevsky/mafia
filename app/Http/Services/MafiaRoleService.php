    public function randomRoles(int $table_id)
    {
        // 1. Загружаем пользователей с их вероятностями (баффами)
        // Напоминание: в модели Account для связи probabilities() должен стоять ->wherePivot('is_activated', 0)
        $users = Account::with('probabilities')
            ->where('table_id', $table_id)
            ->get();

        // Проверка на минимальное количество игроков
        if ($users->count() < 9) {
            return 'Недостаточно игроков';
        }

        if ($users->isEmpty()) {
            return false;
        }

        $usersCount = $users->count();

        // Проверяем наличие раскладки под текущее количество игроков
        if (!isset($this->layouts[$usersCount])) {
            return 'Нет доступной раскладки ролей для такого количества игроков';
        }

        // 2. Сброс старых ролей у всех игроков за этим столом
        foreach ($users as $user) {
            if ($user->role !== null) {
                $user->update(['role' => null]);
            }
        }

        // 3. Выбираем случайную раскладку ролей (колоду)
        $options = $this->layouts[$usersCount];
        $layout = $options[array_rand($options)];

        // Превращаем раскладку в коллекцию для удобной работы
        $availableRoles = collect($layout);

        // // --- 4. Назначение роли «Дон» по рейтингу ---
        // $donIndex = $availableRoles->search(fn($role) => mb_strtolower($role) === 'дон');

        // if ($donIndex !== false) {
        //     // Ищем кандидатов с рейтингом >= 300
        //     $candidatesWithRating = $users->filter(fn($u) => ($u->rating ?? 0) >= 300);

        //     // Если такие есть — берем рандомного среди них, если нет — рандомного вообще
        //     $donUser = $candidatesWithRating->isNotEmpty() ? $candidatesWithRating->random() : $users->random();

        //     // Сохраняем оригинальный регистр роли из колоды через метод update
        //     $donUser->update(['role' => $availableRoles[$donIndex]]);

        //     // Удаляем Дона из колоды и переиндексируем массивы
        //     $availableRoles->forget($donIndex);
        //     $availableRoles = $availableRoles->values();
        // }


        // --- 4. Назначение роли «Дон» случайным образом ---
        $donIndex = $availableRoles->search(fn($role) => mb_strtolower($role) === 'дон');

        if ($donIndex !== false) {
            // Берем абсолютно случайного пользователя из общего списка
            $donUser = $users->random();

            // Сохраняем оригинальный регистр роли из колоды через метод update
            $donUser->update(['role' => $availableRoles[$donIndex]]);

            // Удаляем Дона из колоды и переиндексируем массивы
            $availableRoles->forget($donIndex);
            $availableRoles = $availableRoles->values();
        }

        // --- 5. Сбор баффов в изолированный массив (без изменения самой модели) ---
        $playerBuffs = []; // Формат: [player_id => ['роль1', 'роль2', ...]]

        foreach ($users as $player) {
            // Пропускаем игрока, если ему уже досталась роль Дона
            if ($player->role !== null) {
                continue;
            }

            $wantedRoles = [];

            if ($player->probabilities && $player->probabilities->isNotEmpty()) {
                foreach ($player->probabilities as $probabilityModel) {
                    $rawText = $probabilityModel->text ?? '[]';

                    // Нормализуем JSON-строку (заменяем одинарные кавычки на двойные)
                    $normalizedJson = str_replace("'", '"', $rawText);
                    $decoded = json_decode($normalizedJson, true);

                    if (is_array($decoded)) {
                        // Приводим все роли к нижнему регистру для точного сравнения
                        $wantedRoles = array_merge($wantedRoles, array_map('mb_strtolower', $decoded));
                    }
                }
            }

            if (!empty($wantedRoles)) {
                // Получаем список всех УНИКАЛЬНЫХ ролей, которые В ПРИНЦИПЕ есть в текущей колоде (в нижнем регистре)
                $currentLayoutRoles = $availableRoles->map('mb_strtolower')->unique()->toArray();

                // Фильтруем баффы игрока: оставляем ТОЛЬКО те роли, которые есть в текущей раскладке
                $filteredRoles = array_intersect(array_unique($wantedRoles), $currentLayoutRoles);

                if (!empty($filteredRoles)) {
                    $playerBuffs[$player->id] = $filteredRoles;
                }
            }
        }

        // --- 6. Раздача ролей игрокам с купленными баффами ---
        // Получаем коллекцию свободных игроков, у которых есть баффы, и перемешиваем их
        $playersWithBuffs = $users->filter(fn($u) => isset($playerBuffs[$u->id]))->shuffle();

        foreach ($playersWithBuffs as $player) {
            // На всякий случай проверяем, свободен ли еще игрок
            if ($player->role !== null) {
                continue;
            }

            $playerRoles = $playerBuffs[$player->id];

            // Ищем, какие из желаемых ролей игрока СЕЙЧАС доступны в колоде карт
            $matchedAvailableRoles = $availableRoles->filter(function ($role) use ($playerRoles) {
                return in_array(mb_strtolower($role), $playerRoles);
            });

            // Если совпадения найдены — выдаем одну из этих ролей случайным образом
            if ($matchedAvailableRoles->isNotEmpty()) {
                $chosenRoleKey = $matchedAvailableRoles->keys()->random();
                $chosenRoleName = $availableRoles[$chosenRoleKey];

                // Обновляем только поле role в БД
                $player->update(['role' => $chosenRoleName]);

                // --- АКТИВАЦИЯ БАФФА В PIVOT ТАБЛИЦЕ ---
                foreach ($player->probabilities as $probabilityModel) {
                    $rawText = $probabilityModel->text ?? '[]';
                    $normalizedJson = str_replace("'", '"', $rawText);
                    $decoded = json_decode($normalizedJson, true);

                    if (is_array($decoded)) {
                        $lowercaseDecoded = array_map('mb_strtolower', $decoded);

                        // Если этот бафф содержал ту роль, которую мы только что выдали игроку
                        if (in_array(mb_strtolower($chosenRoleName), $lowercaseDecoded)) {
                            // Обновляем поля в промежуточной таблице account_probabilities
                            $player->probabilities()->updateExistingPivot($probabilityModel->id, [
                                'is_activated' => 1,
                                'table_id'     => $table_id
                            ]);
                            break; // Выходим из цикла баффов игрока, активировав нужный
                        }
                    }
                }

                // Исключаем выданную карту из колоды и обновляем индексы коллекции
                $availableRoles->forget($chosenRoleKey);
                $availableRoles = $availableRoles->values();
            }
        }

        // --- 7. Раздача оставшихся ролей в колоде игрокам БЕЗ баффов ---
        foreach ($availableRoles as $role) {
            // Берем игроков, у которых до сих пор роль равна null
            $remainingPlayers = $users->filter(fn($u) => $u->role === null);

            if ($remainingPlayers->isEmpty()) {
                break;
            }

            // Выбираем абсолютно случайного свободного игрока и записываем ему роль
            $selectedPlayer = $remainingPlayers->random();
            $selectedPlayer->update(['role' => $role]);
        }





        $users = Account::with('immunities')->where('table_id', $table_id)->get();


        foreach ($users as $user) {
            $user->active = (int)$user->active;
            $user->rating = (int)$user->rating;
            $user->club_id = (int)$user->club_id;
            $user->count = (int)$user->count;
            // $user->is_alive = (int)$user->is_alive;
            $user->is_vote = (int)$user->is_vote;
            $user->number = (int)$user->position;
            $user->position = (int)$user->position;
            $user->number = (int)$user->number;
            $user->start_game = (int)$user->start_game;
            $user->target = (int)$user->target;
            $user->is_alive = 1;
            if (!$user->first_game) {
                $user->first_game = Carbon::now();
            }
            $user->save();
        }
        $table = Table::find($table_id);

        $game = Game::find($table->game_id);
        $map = [
            'Дон',
            'Шулер',
            'Приспешник',
            'Мафия'
        ];


        foreach ($users as $account) {

            $account->game_id = $game->id;
            if (in_array($account->role, $map)) {
                $account->character = 'N';
            } else {
                $account->character = 'Y';
            }
        }

        $oborotens = $users->where('role', 'Оборотень');
        $mafias = $users->where('role', 'Мафия');




        return true;
    }
