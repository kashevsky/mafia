    public function show()
    {
        $account = session()->get('account');

        $account = Account::with([
            'transactions',
            'club',
            'achievements' => fn($q) => $q->select('id', 'text', 'account_id'),
            'immunities',
        ])->findOrFail($account->id);

        // 1. Присваиваем заголовки, группируем по ним, считаем количество и сохраняем текст
        $groupedAchievements = $account->achievements
            ->each(function ($achievement) {
                $achievement->title = $this->getTitle($achievement->text);
            })
            ->groupBy('title')
            ->map(function ($items, $title) {
                return [
                    'title' => $title,
                    'count' => $items->count(),
                    'text'  => $items->first()->text, // Сохраняем текст ачивки для модалки
                ];
            })
            ->values();

        // 2. Заменяем старый список ачивок на сгруппированный со всеми полями
        $account->setRelation('achievements', $groupedAchievements);

        $club = Club::with('games')->find($account->club_id);

        return view('account.show', compact('account', 'club'));
    }


    public function update(Request $request)
    {
        $params = $request->all();


        $account = session()->get('account');
        $account = Account::find($account->id);

        if (isset($params['password'])) {
            $account->password = $params['password'];
        }
        if (isset($params['gender'])) {
            $account->gender = $params['gender'];
        }
        if (isset($params['name'])) {
            $account->name = $params['name'];
        }
        if (isset($params['nickname'])) {
            $account->nickname = $params['nickname'];
        }
        if (isset($params['messenger'])) {
            $account->messenger = $params['messenger'];
        }
        if (isset($params['email'])) {
            $account->email = $params['email'];
        }
        if (isset($params['phone'])) {
            $account->phone = $params['phone'];
        }
        if (isset($params['birthday'])) {
            $account->birth = $params['birthday'];
        }
        if (isset($params['bio'])) {
            $account->bio = $params['bio'];
        }

        if (isset($params['avatar'])) {
            if (isset($params['avatar'])) {
                if ($params['avatar']) {
                    $file = $params['avatar'];
                    $name = $file->getClientOriginalName();
                    $file->move(public_path('uploads/avatars'), $name);
                    $account->avatar = '/uploads/avatars' . '/' . $name;
                }
            }
        }

        $account->save();

        return json_encode($account);
    }
    public function changeRole(Request $request)
    {
        // Берём массив по правильному ключу — 'id' (как в твоём дампе)
        $players = $request->input('id', []);

        if (empty($players)) {
            return response()->json(['error' => 'Массив игроков пуст'], 400);
        }

        // Фильтруем тех, у кого роль должна стать 'Приспешник'
        $henchmenIds = collect($players)
            ->filter(fn($player) => $player['role'] === 'Приспешник')
            ->pluck('id')
            ->all();

        if (empty($henchmenIds)) {
            return response()->json([
                'message' => 'Нет игроков с ролью Приспешник для обновления'
            ]);
        }

        $count = Account::whereIn('id', $henchmenIds)
            ->update(['role' => 'Приспешник']);

        return response()->json([
            'success' => true,
            'updated_count' => $count,
            'ids' => $henchmenIds
        ]);
    }

    public function activateImmunity($immunity_id)
    {
        $account = session()->get('account');
        $account = Account::find($account->id);
        $account_immunity = AccountImmunity::where('account_id', $account->id)->where('immunity_id', $immunity_id)->first();
        $account_immunity->is_active = 1;
        $account_immunity->save();
        return redirect()->back();
    }
